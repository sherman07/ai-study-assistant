            draw.rounded_rectangle(box, radius=10, fill="#f8fcff", outline="#c4d8e8", width=1)
            write_text((x1 + 12, y1 + 8), title_value, 20, fill=text, bold=True, max_width=x2 - x1 - 24, max_lines=1)
